export function getCountryVoiceProfile(languageCode: string): CountryVoiceProfile {
  return (
    AI_COUNTRY_VOICES.find((v) => v.languageCode === languageCode) || AI_COUNTRY_VOICES[0]
  );
}

export function getVoicePersonaSpec(languageCode: string, gender: VoiceGender): VoicePersonaSpec {
  const profile = getCountryVoiceProfile(languageCode);
  return gender === 'male' ? profile.male : profile.female;
}
