export function getRecommendedGenreForModule(moduleId: AppModuleId): MusicGenreId {
  switch (moduleId) {
    case 'fitness':
      return 'phonk';
    case 'languages':
    case 'timer':
      return 'lofi';
    case 'meditation':
      return 'zen';
    case 'games':
      return 'arcade';
    case 'nutrition':
    case 'assistant':
      return 'vpop';
    case 'dashboard':
    default:
      return 'usuk';
  }
}

export function filterTracksByGenre(genre: 'all' | MusicGenreId): MusicTrack[] {
  if (genre === 'all') return MUSIC_TRACKS;
  return MUSIC_TRACKS.filter((t) => t.genre === genre);
}

export function getDefaultTrackForGenre(genre: MusicGenreId): MusicTrack {
  return MUSIC_TRACKS.find((t) => t.genre === genre) || MUSIC_TRACKS[0];
}
